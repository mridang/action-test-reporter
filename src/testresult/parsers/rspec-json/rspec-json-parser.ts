/**
 * @file Parses the JSON report written by RSpec.
 */

import {
  TestCaseResult,
  TestGroupResult,
  TestRunResult,
  TestSuiteResult,
} from '../../test-results.js';
import { isRecord } from '../../../record-guard.js';
import type { ParseOptions, TestParser } from '../../test-parser.js';
import type { TestCaseError, TestExecutionResult } from '../../test-results.js';
import type { RspecJson, RspecExample } from './rspec-json-types.js';

const RSPEC_BACKTRACE_LOCATION = /^(.*?):(\d+):/u;

/**
 * Tells whether a parsed value has the root structure of an RSpec JSON report.
 * @param value - The parsed value.
 * @returns True when the value has the expected root.
 * @example
 * const supported = isRspecJson(parsed);
 */
function isRspecJson(value: unknown): value is RspecJson {
  return (
    isRecord(value) && Array.isArray(value.examples) && isRecord(value.summary)
  );
}

/**
 * Parser for JSON reports generated by the RSpec JSON formatter.
 */
export class RspecJsonParser implements TestParser {
  constructor(readonly options: ParseOptions) {}

  async parse(path: string, content: string): Promise<TestRunResult> {
    const mocha = this.getRspecJson(path, content);
    const result = this.getTestRunResult(path, mocha);
    result.sort(true);
    return result;
  }

  private getRspecJson(path: string, content: string): RspecJson {
    try {
      const report: unknown = JSON.parse(content);
      if (!isRspecJson(report)) {
        throw new TypeError('The content is not an RSpec JSON report');
      }
      return report;
    } catch (error) {
      throw new Error(`Invalid JSON at ${path}\n\n${String(error)}`, {
        cause: error,
      });
    }
  }

  private getTestRunResult(
    resultsPath: string,
    rspec: RspecJson,
  ): TestRunResult {
    const resultByStatus = new Map<string, TestExecutionResult>([
      ['failed', 'failed'],
      ['passed', 'success'],
      ['pending', 'skipped'],
    ]);

    const entries = rspec.examples.flatMap((test) => {
      const result = resultByStatus.get(test.status);
      return result === undefined
        ? []
        : [{ test, ...this.processTest(test, result) }];
    });

    const suites = Array.from(
      new Set(rspec.examples.map((test) => test.file_path)),
      (path) => {
        const inSuite = entries.filter(
          (entry) => entry.test.file_path === path,
        );
        return new TestSuiteResult(
          path,
          Array.from(
            new Set(inSuite.map((entry) => entry.groupName)),
            (groupName) =>
              new TestGroupResult(
                groupName,
                inSuite
                  .filter((entry) => entry.groupName === groupName)
                  .map((entry) => entry.testCase),
              ),
          ),
        );
      },
    );
    return new TestRunResult(resultsPath, suites, rspec.summary.duration);
  }

  private processTest(test: RspecExample, result: TestExecutionResult) {
    const groupName =
      test.full_description === test.description
        ? null
        : test.full_description
            .slice(0, test.full_description.length - test.description.length)
            .trimEnd();

    const error = this.getTestCaseError(test);
    const testCase = new TestCaseResult(
      test.full_description,
      result,
      test.run_time ?? 0,
      error,
    );
    return { groupName, testCase };
  }

  private getTestCaseError(test: RspecExample): TestCaseError | undefined {
    const backtrace = test.exception?.backtrace;
    const message = test.exception?.message;
    if (backtrace === undefined) {
      return undefined;
    }

    const details = backtrace.join('\n');

    const src = this.getExceptionSource(backtrace);
    const path = src?.path;
    const line = src?.line;

    return {
      path,
      line,
      message,
      details,
    };
  }

  private getExceptionSource(
    backtrace: string[],
  ): { path: string; line: number } | undefined {
    const re = RSPEC_BACKTRACE_LOCATION;

    return backtrace
      .map((text) => re.exec(text))
      .flatMap((match) =>
        match?.[1].startsWith('./')
          ? [{ path: match[1], line: Number.parseInt(match[2], 10) }]
          : [],
      )
      .at(0);
  }
}
