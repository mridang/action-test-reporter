/**
 * @file Parses Visual Studio TRX test results from .NET test runs.
 */

import { parseStringPromise } from 'xml2js';

import type {
  ErrorInfo,
  Outcome,
  TrxReport,
  UnitTest,
  UnitTestResult,
} from './dotnet-trx-types.js';
import type { ParseOptions, TestParser } from '../../test-parser.js';

import { getBasePath, normalizeFilePath } from '../../utils/path-utilities.js';
import { parseIsoDate, parseNetDuration } from '../../utils/parse-utilities.js';

import type { TestCaseError, TestExecutionResult } from '../../test-results.js';
import {
  TestCaseResult,
  TestGroupResult,
  TestRunResult,
  TestSuiteResult,
} from '../../test-results.js';

const DOTNET_EXCEPTION_LOCATION = / in (.+):line (\d+)$/;

/**
 * Matches a line break together with the carriage returns in front of it. The lookbehind makes the match start at
 * the first carriage return of a run, so a long run of carriage returns without a line feed is scanned only once.
 */
export const STACK_TRACE_LINE_BREAK = /(?<!\r)\r*\n/;

class TestClass {
  constructor(readonly name: string) {}
  readonly tests: Test[] = [];
}

class Test {
  constructor(
    readonly name: string,
    readonly outcome: Outcome,
    readonly duration: number,
    readonly error?: ErrorInfo,
  ) {}

  get result(): TestExecutionResult | undefined {
    switch (this.outcome) {
      case 'Passed': {
        return 'success';
      }
      case 'NotExecuted': {
        return 'skipped';
      }
      case 'Failed': {
        return 'failed';
      }
      default: {
        return undefined;
      }
    }
  }
}

/**
 * Parser for TRX reports generated by Visual Studio and other .NET test runners.
 */
export class DotnetTrxParser implements TestParser {
  assumedWorkDir: string | undefined;

  constructor(readonly options: ParseOptions) {}

  async parse(path: string, content: string): Promise<TestRunResult> {
    const trx = await this.getTrxReport(path, content);
    const tc = this.getTestClasses(trx);
    const tr = this.getTestRunResult(path, trx, tc);
    tr.sort(true);
    return tr;
  }

  private async getTrxReport(
    path: string,
    content: string,
  ): Promise<TrxReport> {
    try {
      return (await parseStringPromise(content)) as TrxReport;
    } catch (error) {
      throw new Error(`Invalid XML at ${path}\n\n${String(error)}`);
    }
  }

  private getTestClasses(trx: TrxReport): TestClass[] {
    if (
      trx.TestRun.TestDefinitions === undefined ||
      trx.TestRun.Results === undefined ||
      !trx.TestRun.TestDefinitions.some(
        (td) => td.UnitTest && Array.isArray(td.UnitTest),
      )
    ) {
      return [];
    }

    const unitTests: { [id: string]: UnitTest } = {};
    for (const td of trx.TestRun.TestDefinitions) {
      for (const ut of td.UnitTest) {
        unitTests[ut.$.id] = ut;
      }
    }

    const unitTestsResults = trx.TestRun.Results.flatMap(
      (r) => r.UnitTestResult,
    ).flatMap((result) => ({
      result,
      test: unitTests[result.$.testId],
    }));

    const testClasses: { [name: string]: TestClass } = {};
    for (const r of unitTestsResults) {
      const testClassName = r.test.TestMethod[0].$.className ?? 'Unclassified';
      let tc = testClasses[testClassName] as TestClass | undefined;
      if (tc === undefined) {
        tc = new TestClass(testClassName);
        testClasses[tc.name] = tc;
      }
      const error = this.getErrorInfo(r.result);
      const durationAttribute = r.result.$.duration;
      const duration = durationAttribute
        ? parseNetDuration(durationAttribute)
        : 0;

      const resultTestName = r.result.$.testName;
      const testName =
        resultTestName.startsWith(testClassName) &&
        resultTestName.codePointAt(testClassName.length) === '.'.codePointAt(0)
          ? resultTestName.slice(testClassName.length + 1)
          : resultTestName;

      const test = new Test(testName, r.result.$.outcome, duration, error);
      tc.tests.push(test);
    }

    return Object.values(testClasses);
  }

  private getTestRunResult(
    path: string,
    trx: TrxReport,
    testClasses: TestClass[],
  ): TestRunResult {
    const times = trx.TestRun.Times[0].$;
    const totalTime =
      parseIsoDate(times.finish).getTime() -
      parseIsoDate(times.start).getTime();

    const suites = testClasses.map((testClass) => {
      const tests = testClass.tests.map((test) => {
        const error = this.getError(test);
        return new TestCaseResult(test.name, test.result, test.duration, error);
      });
      const group = new TestGroupResult(null, tests);
      return new TestSuiteResult(testClass.name, [group]);
    });

    return new TestRunResult(path, suites, totalTime);
  }

  private getErrorInfo(testResult: UnitTestResult): ErrorInfo | undefined {
    if (testResult.$.outcome !== 'Failed') {
      return undefined;
    }

    const output = testResult.Output;
    return output?.length > 0 && output[0].ErrorInfo?.length > 0
      ? output[0].ErrorInfo[0]
      : undefined;
  }

  private getError(test: Test): TestCaseError | undefined {
    if (!this.options.parseErrors || !test.error) {
      return undefined;
    }

    const error = test.error;
    if (
      !Array.isArray(error.Message) ||
      error.Message.length === 0 ||
      !Array.isArray(error.StackTrace) ||
      error.StackTrace.length === 0
    ) {
      return undefined;
    }

    const stackTrace = test.error.StackTrace[0];
    const message = `${test.error.Message[0]}\n${stackTrace}`;
    let path;
    let line;

    const src = this.exceptionThrowSource(stackTrace);
    if (src) {
      path = src.path;
      line = src.line;
    }

    return {
      path,
      line,
      message,
      details: message,
    };
  }

  private exceptionThrowSource(
    stackTrace: string,
  ): { path: string; line: number } | undefined {
    const lines = stackTrace.split(STACK_TRACE_LINE_BREAK);
    const re = DOTNET_EXCEPTION_LOCATION;
    const { trackedFiles } = this.options;

    for (const text of lines) {
      const match = re.exec(text);
      if (match !== null) {
        const [, fileString, lineString] = match;
        const filePath = normalizeFilePath(fileString);
        const workDir = this.getWorkDir(filePath);
        const file = workDir ? filePath.slice(workDir.length) : undefined;
        if (file !== undefined && trackedFiles.includes(file)) {
          const line = Number.parseInt(lineString);
          return { path: file, line };
        }
      }
    }
  }

  private getWorkDir(path: string): string | undefined {
    return (
      this.options.workDir ??
      this.assumedWorkDir ??
      (this.assumedWorkDir = getBasePath(path, this.options.trackedFiles))
    );
  }
}
